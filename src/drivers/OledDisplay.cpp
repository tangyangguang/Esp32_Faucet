const std::uint8_t* glyph(char c) {
    if (c >= 'a' && c <= 'z') {
        c = static_cast<char>(c - 'a' + 'A');
    }
    if (c < ' ' || c > 'Z') {
        c = '?';
    }
    return kFont5x7[c - ' '];
}

